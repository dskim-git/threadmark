/**
 * 개인정보 처리방침과 삭제 안내. (17-B)
 *
 * **이 파일이 그 글의 유일한 원본이다.** `/privacy`와 `/data-deletion`이
 * 같은 글을 본다. 두 곳에 나눠 적으면 한쪽만 갱신되어 어긋난다.
 * 사용법(`src/lib/guide/content.ts`)과 같은 방식이다.
 *
 * **방침이 실제와 어긋나면 없는 것보다 나쁘다.** 사용법이 어긋나면 사용자가
 * 헤매는 데서 끝나지만, 방침이 어긋나면 **하지 않는 일을 한다고 적어둔 것**이
 * 되거나 **하는 일을 감춘 것**이 된다. 둘 다 약속을 어긴 것이다.
 *
 * 실제로 초안이 그랬다. 밖에 맡기는 곳 표에 아직 쓰지도 않는 Kakao·TMDB·
 * YouTube가 적혀 있었고, 정작 쓰고 있는 Crossref·MusicBrainz·iTunes는
 * 빠져 있었다. 말로만 적은 약속은 잊힌다.
 *
 * 그래서 `tests/legal-coverage.test.mjs`가 이 파일을 붙잡는다. 특히
 * **밖으로 요청을 보내는 곳이 늘어나면 이 표에도 없으면 검사가 실패한다.**
 * `OUTGOING_HEADER_SETS`와 맞춰 보는 방식이며, 그 목록은 헤더 검사도 함께
 * 쓰고 있다. 하나를 늘리면 두 검사가 같이 따라온다.
 *
 * 글을 쓸 때
 *   - 쉬운 말로 쓴다. "처리위탁"보다 "밖에 맡기는 곳"이 먼저 읽힌다.
 *   - **모르는 것을 아는 척 적지 않는다.** 정하지 못한 것은 정하지 못했다고
 *     적는다. 지금은 제한적으로 운영 중이고, 읽는 사람도 그것을 알아야 한다.
 *   - 아직 없는 기능을 적지 않는다.
 *
 * **문의할 주소는 여기 적지 않는다.** 이 저장소는 공개되어 있고, 운영자
 * 메일 주소가 코드에 들어가는 것을 막는 검사가 따로 있다. 주소는
 * `contact.ts`가 환경변수에서 읽는다.
 *
 * **이 파일에 다른 것을 import하지 않는다.** 검사가 이 글만 따로 들여다볼 수
 * 있어야 하고, 무언가를 끌어오면 그 사슬이 전부 따라온다. 헤더 묶음과 맞춰
 * 보는 일은 검사가 한다. `request-headers.ts`가 같은 이유로 그렇게 되어 있다.
 *
 * 데이터베이스 의존성이 없는 순수 모듈이라 단위 검사로 검증한다.
 */

