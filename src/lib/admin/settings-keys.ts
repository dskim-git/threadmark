/**
 * 운영 설정의 열쇠와 받을 수 있는 범위. (19-F)
 *
 * 왜 `settings.ts`에서 빼냈는가
 *   그 파일은 Supabase 클라이언트를 물고 있어서 `node --test`가 읽지
 *   못한다. `@/` 별칭을 풀 수 없기 때문이다. **검사가 부르는 모듈은
 *   잎사귀로 둔다.** (AGENTS.md 2절)
 *
 *   그런데 이 값들은 **검사가 꼭 봐야 하는 것**이다. 열쇠 이름이 한 글자만
 *   달라도 설정이 조용히 안 바뀌고, 범위가 데이터베이스 제약과 어긋나면
 *   화면이 받아 놓고 데이터베이스가 거부한다. 둘 다 오류가 나지 않는다.
 *
 *   `settings.ts`가 이것을 다시 내보내므로 부르는 쪽은 그대로다.
 *
 * **이 파일은 아무것도 들여오지 않는다.**
 */

/**
 * 신규 가입자를 승인 대기 상태로 둘지 결정하는 설정 키.
 *
 * 값을 실제로 사용하는 곳은 애플리케이션이 아니라 데이터베이스의
 * `handle_new_user` 트리거다. 화면은 그 값을 보여주고 바꿀 뿐이다.
 */
export const REQUIRE_USER_APPROVAL_KEY = "require_user_approval";

/**
 * 한 달에 AI에 쓸 돈(USD)을 담은 설정 키. (19-F)
 *
 * 이 값을 **데이터베이스가 쓰지 않는다.** 앱이 읽어 한 사람 몫을 셈하고,
 * `ai_monthly_budget_share()`가 그 나눗셈을 한다.
 */
export const AI_MONTHLY_BUDGET_KEY = "ai_monthly_budget_usd";

/**
 * 예산을 얼마까지 적을 수 있는가.
 *
 * **위쪽은 데이터베이스 제약과 같은 값이어야 한다.**
 * (`app_settings_ai_monthly_budget_usd_is_number`) 어긋나면 화면은 받아
 * 놓고 데이터베이스가 거부하는데, 그때 나오는 말로는 무엇이 잘못됐는지
 * 알 수 없다. `tests/admin-settings-keys.test.mjs`가 둘을 견준다.
 *
 * 위쪽을 둔 까닭은 오타다. `5`를 적으려다 `500`이 들어가면 **막는 자리가
 * 사라진다.** Anthropic Console의 예산이 바깥에서 막아 주지만, 그때는
 * 기능이 통째로 멈추는 모양으로 나타난다.
 *
 * 아래쪽은 제약(`> 0`)보다 **엄해도 된다.** 느슨하면 거부당할 값을 받게
 * 되므로 그쪽만 막는다. 아주 작은 값을 받는 까닭은 **한도에 걸린 화면을
 * 눌러 확인하려면** 예산을 잠깐 작게 둘 수 있어야 하기 때문이다.
 */
export const AI_BUDGET_MIN_USD = 0.0001;
export const AI_BUDGET_MAX_USD = 100;
