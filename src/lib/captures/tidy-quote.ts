/**
 * 집은 문장을 얼마나 다듬었는가. (2026-10-04, 사용자 요청)
 *
 * > 가끔 pdf에서 긁어온 원문을 약간 수정해서 저장해야 할 때가 있어.
 * > (띄어쓰기가 이상하다던가 마침표까지 드래그가 안되었다던가)
 *
 * 다듬는 길을 열면서 **그 길이 고쳐 쓰는 길이 되지 않게** 재는 자리다.
 *
 * 무엇을 재는가
 *   **글자를 빼고 센다.** 띄어쓰기를 고치고 마침표를 더하는 일은 공백과
 *   문장부호만 바뀌므로, 그것을 빼고 나면 **아무것도 달라지지 않는다.**
 *   반대로 낱말을 바꾸거나 문장을 다시 쓰면 바로 드러난다.
 *
 *   길이만 재는 길도 있었다. 틀린다. `있소`를 `없소`로 바꾸면 길이가 같고,
 *   **뜻이 뒤집히는데 아무 말도 하지 않는다.**
 *
 * 왜 막지 않는가
 *   무엇이 정당한 인용인지는 우리가 정할 수 없다. 쓰는 사람이 정할 일이다.
 *   우리는 **선을 넘고 있다는 것만 말한다.** 막으면 멀쩡한 다듬기까지
 *   막히고, 그러면 저장한 뒤 `수정`으로 들어가 고치게 된다. 돌아가는 길이
 *   생기면 재는 뜻이 없어진다.
 *
 * **이 파일은 아무것도 import하지 않는다.** 검사가 직접 부른다.
 * (`AGENTS.md` 6절)
 */

/**
 * 견줄 때 빼는 글자.
 *
 * 공백과 흔한 문장부호다. 드래그가 집어오며 어긋나는 것이 이것들이고,
 * **그것만 고친 것은 다듬은 것**으로 본다.
 *
 * 따옴표를 넣은 까닭. PDF는 곧은 따옴표를 둥근 따옴표(`\u201c`, `\u201d`)로
 * 따로 담는데, 이어 붙이다 보면 한쪽만 들어온다. 그 짝을 맞추는 일도
 * 다듬기다.
 *
 * **글자를 그대로 적지 않고 번호로 적는다.** 둥근 따옴표를 소스에 그대로
 * 두었더니 어딘가에서 곧은 따옴표로 바뀌어 들어가 목록에서 빠졌다.
 * 검사가 그것을 붙잡았다. 눈으로는 구분되지 않는 글자다.
 */
const IGNORED =
  /[\s.,;:!?\u00b7\u2026"'\u201c\u201d\u2018\u2019\u300c\u300d\u300e\u300f\uff08\uff09()[\]{}<>\u2013\u2014-]/gu;

/** 뜻을 이루는 글자만 남긴다. */
function core(value: string): string {
  return value.replace(IGNORED, "");
}

/**
 * 다듬은 것을 넘어 **고쳐 쓴 것**인가.
 *
 * 공백과 문장부호를 뺀 글자가 달라졌으면 참이다. 한 글자라도 다르면
 * 알린다. **느슨하게 봐주면 재는 뜻이 없다.**
 *
 * 둘이 같거나, 다듬지 않았으면 거짓이다.
 */
export function heavilyChanged(picked: string, tidied: string): boolean {
  return core(picked) !== core(tidied);
}

/**
 * 담길 글을 고른다.
 *
 * 다듬지 않았거나 다 지웠으면 **집은 그대로**다. 원문 없는 인용은 인용이
 * 아니고(설계 문서 2.4절) 데이터베이스의 제약조건도 그것을 막는다.
 * 여기서 먼저 걸러 **저장이 실패하는 대신 집은 것이 담기게** 한다.
 */
export function quoteToSave(picked: string, tidied: string | null): string {
  const trimmed = tidied?.trim() ?? "";

  return trimmed.length > 0 ? trimmed : picked;
}
