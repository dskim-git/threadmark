/**
 * 사용법. (AGENTS.md 4절의 15-F)
 *
 * **이 파일이 사용법의 유일한 원본이다.**
 *
 * 같은 글이 두 곳에 나온다.
 *   `/guide`          처음 오는 사람이 처음부터 끝까지 읽는 화면
 *   물음표 단추       그 기능 옆에서 그 대목만 바로 보여주는 창
 *
 * 두 곳에 나눠 적으면 한쪽만 갱신되어 어긋난다. `CLAUDE.md`가 지침을 한 곳에만
 * 두는 것과 같은 생각이다. 여기 한 번 적으면 두 곳에 함께 나온다.
 *
 * **사용법이 코드와 어긋나면 없는 것보다 나쁘다.** 처음 쓰는 사람이 사용법대로
 * 했는데 그 단추가 없으면, 앱이 고장났다고 생각하거나 자기가 잘못한 줄 안다.
 * 아예 없었으면 화면을 뒤져보기라도 했을 것이다.
 *
 * 그래서 `tests/guide-coverage.test.mjs`가 이 파일을 붙잡고 있다.
 *   - 앱 메뉴에 있는 화면이 모두 여기 설명되어 있는가
 *   - 화면에 붙인 물음표 단추가 가리키는 대목이 실제로 있는가
 *   - 대목마다 제목·한 줄 요약·순서가 비어 있지 않은가
 *
 * 새 화면을 만들고 사용법을 쓰지 않으면 `npm test`가 실패한다.
 * **기능을 더하는 커밋에서 이 파일도 함께 고친다.**
 *
 * 글을 쓸 때
 *   - 전문 용어 대신 "무엇이 달라지는가"로 쓴다.
 *   - 순서(`steps`)는 손이 움직이는 차례대로 적는다. 화면 이름과 단추
 *     이름은 실제 화면에 보이는 글자 그대로 적는다.
 *   - `notes`에는 "왜 그렇게 되어 있는지"와 "헷갈리기 쉬운 것"을 적는다.
 *   - 아직 없는 기능을 적지 않는다.
 *
 * 데이터베이스 의존성이 없는 순수 모듈이라 단위 검사로 검증한다.
 */

export type GuideTopic = {
  /** 물음표 단추가 가리키는 열쇠. 화면에서 `topic="..."`으로 쓴다. */
  id: string;
  title: string;
  /** 한 줄 요약. 물음표 창의 첫 줄이자 목록의 설명이다. */
  summary: string;
  /** 손이 움직이는 차례. 번호가 붙어 나온다. */
  steps: readonly string[];
  /** 알아두면 좋은 것. 없어도 된다. */
  notes?: readonly string[];
  /**
   * 이 대목이 설명하는 앱 경로.
   *
   * 검사가 "메뉴에 있는 화면이 모두 설명되어 있는가"를 볼 때 쓴다.
   * 설명하는 화면이 따로 없는 대목(전체 흐름 같은 것)은 비워둔다.
   */
  routes?: readonly string[];
};

export type GuideSection = {
  id: string;
  title: string;
  /** 이 묶음이 무엇에 대한 것인지. */
  intro: string;
  topics: readonly GuideTopic[];
};

