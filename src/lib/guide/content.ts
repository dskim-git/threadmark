/** 모든 대목을 한 줄로 펼친 것. 물음표 단추가 열쇠로 찾을 때 쓴다. */
export const GUIDE_TOPICS: readonly GuideTopic[] = GUIDE_SECTIONS.flatMap(
  (section) => section.topics,
);

/** 열쇠로 대목 하나를 찾는다. 없으면 null이다. */
export function findGuideTopic(id: string): GuideTopic | null {
  return GUIDE_TOPICS.find((topic) => topic.id === id) ?? null;
}
