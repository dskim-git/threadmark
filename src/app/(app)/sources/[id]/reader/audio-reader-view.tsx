/**
 * 음성을 들으며 메모를 남기는 자리. (설계 문서 17절, 17-V 2차례, 2026-10-04)
 *
 * **Client Component가 아니다.** `<audio controls>`는 브라우저가 그려 주는
 * 것이라 우리 쪽 자바스크립트가 필요하지 않다. 재생·멈춤·건너뛰기·속도가
 * 전부 거기 들어 있다. 쓸 일이 없는데 `"use client"`를 붙이면 묶음만
 * 커진다.
 *
 * **PDF·그림 작업대와 모양이 다르다.** 그 둘은 좌우로 나누고 창 높이를
 * 재서 채운다. 음성은 그러지 않는다.
 *
 *   PDF   파일 하나에 쪽이 여럿이다. 넓게 펼쳐야 읽힌다
 *   그림  파일 하나가 한 장이다. 크게 봐야 보인다
 *   음성  **볼 것이 없다.** 재생기는 한 줄이면 된다
 *
 * 그래서 재생기를 위에 한 줄로 두고 메모와 기록을 아래에 둔다. 좌우로
 * 나누면 **왼쪽에 한 줄짜리 재생기를 놓고 아래를 통째로 비우는** 모양이
 * 된다.
 *
 * `image-reader-view.tsx`가 "같이 쓰는 조각만 나눠 쓰고 화면은 따로 둔다.
 * 겹치는 것은 조각이지 흐름이 아니다"라고 적어둔 자리다. 음성은 겹치는
 * 조각조차 없다.
 *
 * **사라진 파일은 여기까지 오지 않는다.** 읽기 화면이 그 경우를 먼저
 * 가로채 "Drive에 파일이 없어 열 수 없습니다"를 띄운다. 그림은 **다른 장이
 * 멀쩡해서** 작업대를 여는 예외였고, 음성은 파일 하나가 통째로 안 열리는
 * 것이라 PDF와 같은 자리에 선다. 그래서 이 파일에 그 경우를 또 두지
 * 않는다. **닿지 않는 코드에 "이럴 때는 이렇게 한다"를 적어두면 다음에
 * 읽는 사람이 그것이 도는 줄 안다.**
 *
 * **시점을 기록에 담지 않는다.** `3분 20초에 이 말` 같은 것을 담으려면
 * 기록이 자리를 가리키는 모양(`locator`)을 정해야 하고, 그것은 17-V에서
 * 정하지 않았다. 지금은 자료에 메모를 다는 길을 그대로 쓴다. **정하지
 * 않은 것을 만들지 않는다.** (17-V.9절)
 */

export function AudioReaderView({
  src,
  memoSlot,
  capturesSlot,
}: {
  /**
   * Drive에서 흘러나오는 주소. **공개 링크가 아니다.**
   * 이 경로가 세션을 보고 본인 것만 내보낸다. (설계 문서 2.3절)
   */
  src: string;
  /** 메모 칸. Server Action을 품고 있어 여기서 못 만든다. */
  memoSlot: React.ReactNode;
  /** 서버가 그려 넘긴 기록 목록. 같은 까닭이다. */
  capturesSlot: React.ReactNode;
}) {
  return (
    <div className="flex flex-col gap-4">
      <section className="rounded-2xl bg-zinc-50 px-5 py-5 dark:bg-white/[.04]">
        {/*
          `preload="metadata"`를 쓴다.

          `auto`로 두면 화면을 열기만 해도 파일을 통째로 받아온다. 녹음은
          수십 MB가 흔하고 듣지 않고 지나가는 경우도 있다. `none`으로 두면
          **길이가 표시되지 않아** 얼마나 긴 녹음인지 누르기 전에 알 수
          없다. 머리말만 받으면 길이는 나오고 소리는 누를 때 받는다.
        */}
        <audio controls preload="metadata" src={src} className="w-full">
          {/*
            받쳐 주는 글. 재생기를 못 그리는 브라우저에서 보인다.
            **빈 자리를 남기지 않는다.**
          */}
          이 브라우저는 음성 재생을 지원하지 않습니다.
        </audio>

        <p className="mt-3 text-xs text-zinc-500">
          들으면서 아래에 메모를 남길 수 있습니다. 어느 대목인지는 메모에 직접
          적습니다.
        </p>
      </section>

      {memoSlot}

      {capturesSlot}
    </div>
  );
}
