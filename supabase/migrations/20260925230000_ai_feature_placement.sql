-- =============================================================================
-- AI 갈래에 `자리 추천`을 더한다 (19-D)
-- =============================================================================
-- 설계 문서 19절의 "출처 기반 추천"을 뼈대에 붙인다. 프로젝트에 이어두었지만
-- 아직 어느 자리에도 놓이지 않은 재료들을 놓고, 각각 어느 자리에 어울리는지
-- 한 번에 물어본다.
--
-- 왜 `search`로 적지 않는가
--   같은 Claude를 부르고 돈도 같은 데서 나간다. 그래도 갈래를 나눈다.
--   장부가 답해야 할 물음이 **"이번 달에 얼마나 썼는가"** 하나가 아니라
--   **"왜 이 달에 많이 나왔는가"**이기도 하기 때문이다. 둘을 한 이름으로
--   적으면 뒤엣것에 답할 수 없다.
--
-- 왜 마이그레이션을 따로 만드는가
--   `ALTER TYPE ... ADD VALUE`로 더한 값은 **같은 트랜잭션에서 쓸 수 없다.**
--   (AGENTS.md 6절) Supabase CLI는 마이그레이션 하나를 한 트랜잭션으로
--   돌리므로, 값을 더하는 일과 그 값을 쓰는 일이 같은 파일에 있으면 안 된다.
--
--   여기서는 더하기만 한다. 쓰는 쪽은 앱 코드이고 그것은 이 마이그레이션이
--   끝난 뒤에 돈다. **마이그레이션을 먼저 올리고 그 칸을 읽는 코드를
--   돌린다.** (AGENTS.md 2절)
--
--   16-A-1에서 `translation`과 `search`를 미리 함께 넣어둔 것이 이 함정
--   때문이었다. 그때 `placement`까지 내다보지는 못했다. **미리 넣어두는
--   것으로 다 막을 수는 없다.** 그래서 늘어날 때 파일 하나를 더하는 길이
--   열려 있어야 하고, 이것이 그 예다.
-- =============================================================================

alter type public.ai_feature add value if not exists 'placement';

comment on type public.ai_feature is
  'AI를 부른 기능. 값을 더하려면 이 파일처럼 마이그레이션을 따로 하나 만든다.';
