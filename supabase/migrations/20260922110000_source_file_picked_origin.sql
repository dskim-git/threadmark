-- =============================================================================
-- ThreadMark — 고른 파일(origin = 'picked')
-- =============================================================================
-- 목적
--   Google Picker로 사용자가 이미 가지고 있던 Drive 파일을 고르는 경로를 연다.
--   (설계 문서 10.2절) 12-B에서 source_file_origin을 만들며 예고해 둔 값이다.
--
-- 왜 구분하는가
--   앱이 만든 파일과 사용자가 원래 가지고 있던 파일은 다루는 태도가 달라야 한다.
--
--     upload  ThreadMark가 Drive에 만들었다. 우리가 만든 것이다.
--     picked  사용자가 원래 가지고 있던 것을 고른 것이다.
--
--   설계 문서 10.3절이 말한 orphan 파일 정리를 나중에 만들 때, 이 구분이 없으면
--   "지워도 되는 파일"과 "손대면 안 되는 파일"을 나눌 수 없다.
--   사용자의 원래 파일을 우리가 정리 대상으로 삼는 일은 없어야 한다.
--
-- 트랜잭션 안에서 실행해도 되는가
--   PostgreSQL 12부터 ALTER TYPE ... ADD VALUE는 트랜잭션 안에서도 된다.
--   다만 **같은 트랜잭션 안에서 그 값을 쓸 수는 없다.**
--   그래서 이 마이그레이션은 값을 더하기만 하고 쓰지 않는다.
--   실제로 쓰는 것은 애플리케이션 코드다.
--
-- 재실행 안전성
--   if not exists를 붙였다. 이미 있으면 아무 일도 하지 않는다.
-- =============================================================================

alter type public.source_file_origin add value if not exists 'picked';
