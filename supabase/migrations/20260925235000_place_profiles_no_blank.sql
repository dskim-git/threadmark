-- =============================================================================
-- 장소의 글 칸에 빈 글자를 받지 않는다 (17-1)
-- =============================================================================
-- 설계 문서 17-1.4절. (2026-09-25, 카카오 Local을 눌러보고 알게 된 것)
--
-- 무엇을 겪었나
--   `경복궁`으로 물어본 응답에서 `road_address_name`이 **null이 아니라 빈
--   글자로** 왔다. 열다섯 건 중 둘이 그랬다.
--
--     경복궁 별빛야행   road_address_name: ""
--     경복궁 경회루     road_address_name: ""
--
--   그대로 담으면 화면은 `주소가 있다`고 판단하면서 아무것도 보여주지
--   못한다. **빈 줄만 뜬다.** 오류는 나지 않으므로 화면을 봐도 무엇이
--   잘못됐는지 알 수 없고, 사용자는 주소가 지워진 줄 안다.
--
-- 왜 앱에서만 다듬지 않는가
--   다듬는 코드는 한 곳에 있고, 담는 길이 늘어나면(직접 적기, 다시 받아오기,
--   나중의 해외 검색) 그 길마다 다시 다듬어야 한다. **한 길에서 잊으면
--   빈 글자가 들어오고 아무도 말해주지 않는다.**
--
--   빈 장르 이름을 막아둔 것과 같은 판단이다. (15-E-2c-1, 검사 112)
--
-- `numeric` 칸에는 걸 것이 없다
--   좌표는 범위와 짝을 이미 본다. (20260925234000)
--
-- 왜 파일을 따로 두는가
--   `place_profiles`는 이미 원격에 올라가 있다. 표를 만든 파일을 고치면
--   원격에 적용된 것과 저장소의 것이 어긋난다. 이미 올라간 마이그레이션은
--   고치지 않고 새 파일을 더한다.
--
--   **지금이 제일 싼 때다.** 표가 비어 있어 기존 값을 손볼 일이 없다.
--
-- 재실행 안전성
--   제약조건이 이미 있으면 건너뛴다.
-- =============================================================================

do $$
declare
  v_column text;
begin
  /*
    글을 담는 칸 전부에 같은 규칙을 건다.

    목록으로 도는 까닭은 하나를 빠뜨리기 쉽기 때문이다. 손으로 여섯 번
    적으면 여섯 번째에서 이름을 잘못 쓰고, 그 칸만 조용히 열린 채 남는다.
  */
  foreach v_column in array array[
    'external_id',
    'road_address',
    'address',
    'category',
    'phone',
    'place_url'
  ]
  loop
    if not exists (
      select 1 from pg_constraint
      where conname = 'place_profiles_' || v_column || '_not_blank'
    ) then
      execute pg_catalog.format(
        'alter table public.place_profiles
           add constraint place_profiles_%s_not_blank check (
             %I is null or pg_catalog.btrim(%I) <> %L
           )',
        v_column, v_column, v_column, ''
      );
    end if;
  end loop;
end
$$;

/*
  분류를 통째로 담는다.

  처음에는 카카오의 `category_group_name`(`음식점`, `관광명소`)을 담기로
  했다. **눌러보니 그 칸이 열다섯 건 중 아홉 건에서 비어 있었다.** 하필
  궁 안의 건물들이 그랬다. 근정전·경회루·향원정 모두 분류 없이 온다.

  그대로 만들면 `관광명소`로 걸러볼 때 그것들이 나오지 않고, **오류는
  나지 않는다.** 사용자는 그런 것을 담은 적이 없다고 생각한다.

  그래서 `category_name`을 통째로 담는다. `음식점 > 한식 > 한정식`처럼
  온다. 찾을 수 있는 말이 늘어나고(`한식`으로도 걸린다), 화면에는 마지막
  토막만 보여준다. 담는 것과 보여주는 것을 가른 자리다. (17-1.4절)
*/
comment on column public.place_profiles.category is
  '분류를 통째로(음식점 > 한식 > 한정식). 짧은 분류 칸은 절반 넘게 비어 와서 쓰지 않는다. 화면은 마지막 토막만 보여준다.';
