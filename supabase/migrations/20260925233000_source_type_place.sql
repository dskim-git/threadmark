-- =============================================================================
-- 자료 갈래에 `place`(장소)를 더한다 (17-1)
-- =============================================================================
-- 설계 문서 5.1절과 17-1절. (2026-09-25, 사용자 요청)
--
-- 왜 필요한가
--   수업 준비의 답사지, 여행 준비의 갈 곳, 책 쓰기의 배경이 되는 곳이 모두
--   같은 모양이다. **어딘가를 정해두고, 왜 거기인지 적고, 나중에 그 자리를
--   다시 찾는 일.** 지금은 그것을 담을 자리가 없어 메모에 주소를 적어두는
--   수밖에 없고, 그러면 지도로 열 수도 없고 검색으로 찾기도 어렵다.
--
-- 왜 파일을 따로 두는가
--   `ALTER TYPE ... ADD VALUE`로 더한 값은 **같은 트랜잭션에서 쓸 수 없다.**
--   (AGENTS.md 6절) Supabase CLI는 마이그레이션 하나를 한 트랜잭션으로
--   돌리므로, 값을 더하는 일과 그 값을 쓰는 일이 같은 파일에 있으면 안 된다.
--
--   `place_profiles` 표는 이 값을 쓰지 않는다(자료를 `source_id`로 가리킬
--   뿐이다). 그래도 나눈다. **오늘 같은 자리에서 두 번 막혔다.** 나중에
--   장소에만 걸 제약조건이나 기본값을 더하고 싶어질 때, 파일이 이미 나뉘어
--   있으면 그때 막히지 않는다.
--
--   13-C의 `20260922150000`/`20260922151000`, 19-D의 `20260925230000`이
--   같은 이유로 갈라진 파일들이다.
--
-- 쓰는 쪽은 뒤에 온다
--   이 값을 고르는 화면과 `place_profiles`를 읽는 코드는 이 마이그레이션이
--   올라간 뒤에 돈다. **마이그레이션을 먼저 올리고 그 칸을 읽는 코드를
--   돌린다.** (AGENTS.md 2절)
-- =============================================================================

alter type public.source_type add value if not exists 'place';

comment on type public.source_type is
  '자료 갈래. (설계 문서 5.1절) 값을 더하려면 이 파일처럼 마이그레이션을 따로 하나 만든다.';
