-- =============================================================================
-- sources.owner_id 기본값
-- =============================================================================
-- 배경
--   설계 문서 2.3절에 따라 애플리케이션은 owner_id를 보내지 않는다.
--   값은 sources_set_owner 트리거가 auth.uid()로 채운다.
--
--   그런데 컬럼에 기본값이 없으면 생성된 TypeScript 타입이 owner_id를 필수로 본다.
--   트리거의 존재를 타입 생성기가 알 수 없기 때문이다. 그 결과 코드는
--   보내지 않아도 되는 값을 보내야 하고, 설계 의도와 타입이 어긋난다.
--
-- 조치
--   컬럼 기본값을 auth.uid()로 둔다. 트리거는 그대로 남겨 서버가 보낸 값까지
--   덮어쓰는 역할을 계속한다. 기본값은 타입을, 트리거는 실제 보장을 담당한다.
--
--   auth.uid()가 없는 서비스 컨텍스트에서 owner_id 없이 넣으면 NOT NULL 위반으로
--   분명하게 실패한다. 소유자 없는 자료가 조용히 생기지 않는다.
-- =============================================================================

alter table public.sources
  alter column owner_id set default auth.uid();

comment on column public.sources.owner_id is
  '소유자. 기본값과 트리거가 auth.uid()로 채운다. 클라이언트가 보낸 값은 트리거가 덮어쓴다.';
