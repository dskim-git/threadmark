-- =============================================================================
-- 전사문을 자료마다가 아니라 파일마다 (17-V 4차례 보완)
-- =============================================================================
-- **1차례에 적어둔 전제가 깨졌다. 사용자가 쓰다가 찾았다.**
--
-- > 한 자료에 여러 음성 파일이 있을 수 있는데 지금은 한 자료 내에서 첫번째
-- > 저장된 음성 파일에만 전사문이 저장되는것 같아.
--
-- 블루프린트 17-V.2절이 그 전제와 함께 나갈 길을 적어 두었다.
--
-- > 한 자료에 음성 파일을 여럿 붙이면 전사문은 source_file_id가 가리키는
-- > 그 하나의 것이다. 전제가 깨지는 것이 보이면 unique를 파일 쪽으로
-- > 옮기고 검사의 뽑는 자리를 함께 넓힌다. 짐작으로 미리 넓혀 두지 않는다.
--
-- 그대로 한다. **적어둔 덕에 무엇을 해야 하는지 다시 생각하지 않았다.**
--
-- 무엇이 조용했나
--   오류가 나지 않았다. 두 번째 녹음에 전사문을 적으면 **첫 번째 녹음의
--   전사문이 덮였다.** 자료 하나에 한 줄이라 upsert가 그렇게 돈다.
--   적은 사람은 방금 적은 것만 보고 앞의 것이 사라진 줄 모른다.
--
-- 왜 source_file_id를 not null로 하지 않는가
--   **파일을 떼어도 전사문이 남아야 한다.** (10.4절, 앞 마이그레이션)
--   not null로 하면 그 약속과 부딪힌다. PostgreSQL의 unique는 NULL을
--   여럿 받으므로, nullable + unique가 바라는 뜻을 그대로 적는다.
--
--     파일마다 전사문은 **많아야 하나**
--     파일이 떨어진 전사문은 **여럿 있어도 된다**
--
-- 표 이름은 그대로 둔다
--   `*_profiles`가 이 저장소에서 "자료 하나에 딸린 정보"를 뜻해 왔다.
--   이제 이 표만 **파일 단위**다. 이름을 바꾸면 마이그레이션이 또 필요하고
--   검색 검사가 표 이름을 그 꼴로 뽑으므로 거기도 흔들린다.
--
--   **대신 이름이 더 이상 단위를 말하지 않는다는 것을 적어 둔다.**
--   표 주석과 블루프린트 17-V.2절에 남겼다. 다음에 `*_profiles`를 보고
--   "자료마다 하나겠지"라고 읽는 사람이 있을 자리다.
--
-- 재실행 안전성
--   if exists / if not exists 로 썼다.
-- =============================================================================


-- -----------------------------------------------------------------------------
-- 1. 자료마다 하나라는 제약을 푼다
-- -----------------------------------------------------------------------------
-- 컬럼에 적은 `unique`는 제약조건으로 만들어진다. 이름은 PostgreSQL이
-- 정한 기본값(`<표>_<칸>_key`)이다.

alter table public.audio_profiles
  drop constraint if exists audio_profiles_source_id_key;

-- 자료로 찾는 길은 그대로 쓴다. 한 자료의 전사문을 모아 보여주는 화면이
-- 이 색인을 쓴다. 제약이 사라졌으므로 색인을 따로 둔다.
create index if not exists audio_profiles_source_idx
  on public.audio_profiles (source_id);


-- -----------------------------------------------------------------------------
-- 2. 파일마다 하나로 옮긴다
-- -----------------------------------------------------------------------------
/*
  **부분 색인이 아니라 보통 unique 색인이다.**

  PostgreSQL의 unique 색인은 NULL을 서로 다른 값으로 본다. 그래서
  `where source_file_id is not null`을 붙이지 않아도 파일이 떨어진 줄은
  여럿 있을 수 있다. 붙이면 같은 뜻이 되지만 읽는 사람이 "왜 조건이
  붙었지"를 한 번 더 묻게 된다.

  앞 마이그레이션이 만든 색인(`audio_profiles_source_file_idx`)은 unique가
  아니었다. 같은 칸에 둘을 두지 않는다. 이것으로 갈음한다.
*/
drop index if exists public.audio_profiles_source_file_idx;

create unique index if not exists audio_profiles_source_file_key
  on public.audio_profiles (source_file_id);


-- -----------------------------------------------------------------------------
-- 3. 적어 둔다
-- -----------------------------------------------------------------------------

comment on table public.audio_profiles is
  '녹음 파일 하나의 전사문과 길이. **이름은 *_profiles인데 단위는 자료가 아니라 파일이다.** 한 자료에 녹음이 여럿일 수 있다. (설계 문서 17-V.2절)';

comment on column public.audio_profiles.source_file_id is
  '전사문이 나온 녹음 파일. 파일마다 많아야 하나다. 파일을 떼면 비워지고, 떨어진 전사문은 여럿 있을 수 있다.';

comment on column public.audio_profiles.source_id is
  '어느 자료의 녹음인가. 한 줄에 하나이지만 자료마다 여럿일 수 있다. 검색이 이 칸으로 자료를 찾는다.';
