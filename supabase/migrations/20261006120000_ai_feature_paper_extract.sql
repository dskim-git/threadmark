-- 두 길 다 `src/lib/translation/rate-limit.ts`의 연타 한도만 걸려 있다.
-- 그 파일이 스스로 이렇게 적어 두었다.
--
--   Vercel처럼 요청마다 다른 곳에서 실행될 수 있는 환경에서는 이 한도가
--   생각보다 헐겁게 걸린다. **진짜 상한은 16단계에서 데이터베이스에 둔다.**
--
-- 16단계에서 장부를 만들었는데 **이 둘을 거기 잇지 않았다.** 적어둔 할 일이
-- 적어둔 자리에서 그대로 남아 있었고, 혼자 쓸 때는 드러나지 않았다.
--
-- 한 번 상한이 $0.07이다. 들어가는 글 12,000자에 나오는 글 4,000토큰이다.
-- **싸지 않다.** (VERIFICATION 4-76절)
--
-- 왜 `search`로 적지 않는가
--   `placement`를 따로 둔 것과 같은 까닭이다. 장부가 답해야 할 물음이
--   "이번 달에 얼마나 썼는가" 하나가 아니라 **"왜 이 달에 많이 나왔는가"**
--   이기도 하다. 논문 한 편을 AI로 읽는 것과 물음에 답하는 것은 쓰는 사람의
--   머릿속에서 다른 일이다.
--
-- 왜 마이그레이션을 따로 만드는가
--   `ALTER TYPE ... ADD VALUE`로 더한 값은 **같은 트랜잭션에서 쓸 수 없다.**
--   (AGENTS.md 6절) 여기서는 더하기만 한다. 쓰는 쪽은 앱 코드이고 그것은
--   이 마이그레이션이 끝난 뒤에 돈다.
--
--   `20260925230000`이 `placement`를 더하면서 적어둔 말이 그대로 맞았다.
--   **미리 넣어두는 것으로 다 막을 수는 없다.** 늘어날 때 파일 하나를
--   더하는 길이 열려 있어야 하고, 이것이 그 두 번째 예다.
