-- =============================================================================
-- ThreadMark — 사라진 파일 상태
-- =============================================================================
-- 목적
--   사용자가 Drive에서 파일을 지우거나 옮긴 것을 표시한다.
--
--   설계 문서 10.4절
--     토큰 만료, 권한 취소, 파일 이동·삭제를 구분해 표시한다.
--     Drive 파일이 사라져도 Source와 Capture 메타데이터는 유지한다.
--
--   설계 문서 25절 통합 테스트 8번
--     사용자가 Drive 파일을 삭제하면 복구 가능한 오류 상태가 표시된다.
--
-- 12-B에서 예고해 둔 값이다
--   그때는 이렇게 적었다.
--
--     파일이 사라진 경우를 나타내는 값은 두지 않는다. 그것을 감지하는 기능
--     (설계 문서 9.2절의 파일 변경 감지)이 아직 없어서, 값만 만들어두면
--     아무도 쓰지 않는 상태가 하나 남는다.
--
--   이제 감지하는 기능을 만드니 값을 더한다.
--
--   pending  업로드 중
--   ready    Drive에서 확인했다. 열어볼 수 있다.
--   missing  Drive에 없다. 지웠거나 옮겼다.
--
-- 되돌아갈 수 있는 상태다
--   사라진 것으로 보였다가 다시 찾아질 수 있다. 일시적인 오류였거나,
--   사용자가 휴지통에서 되살렸을 수도 있다. 그래서 missing에서 ready로
--   돌아가는 길을 막지 않는다.
--
--   행을 지우지 않는 이유도 같다. 기록이 그 파일을 가리키고 있고,
--   설계 문서 10.4절이 자료와 기록은 유지하라고 한다.
--
-- 왜 마이그레이션을 둘로 나누었나
--   PostgreSQL은 ALTER TYPE ... ADD VALUE 로 더한 값을 **같은 트랜잭션 안에서**
--   쓰지 못하게 한다. 이 값을 쓰는 가드 함수는 다음 마이그레이션에 둔다.
--   Supabase CLI는 마이그레이션마다 트랜잭션을 따로 잡는다.
--
-- 재실행 안전성
--   if not exists를 붙였다. 이미 있으면 아무 일도 하지 않는다.
-- =============================================================================

alter type public.source_file_status add value if not exists 'missing';
