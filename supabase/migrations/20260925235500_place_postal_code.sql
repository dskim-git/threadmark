-- =============================================================================
-- 장소에 우편번호를 더한다 (17-1)
-- =============================================================================
-- 설계 문서 17-1.4절. (2026-09-25, 사용자 요청)
--
--   > 우편 주소는 다섯자리를 말하는게 맞아.
--
-- 왜 칸을 따로 두는가
--   도로명 주소에 붙여 담으면 우편번호로 찾을 수 없고, 화면에서 떼어
--   보여줄 수도 없다. 같은 칸에 두 가지를 담으면 나중에 가를 수 없다.
--
-- 이름으로 찾을 때는 오지 않는다
--   **카카오의 키워드 검색 응답에는 우편번호가 없다.** 문서로 확인했다.
--   주소 검색 응답에만 `road_address.zone_no`로 들어 있다.
--
--   그래서 이 칸은 **주소로 찾기와 함께** 쓸모가 생긴다. 이름으로 찾아
--   담은 장소는 이 칸이 비어 있고, 그것이 정상이다.
--
-- 모양을 다섯 자리로 못박지 않는다
--   국내 우편번호는 2015년부터 다섯 자리다. 그런데 **해외 장소는 손으로
--   적고, 거기에는 글자가 섞인다.** 영국의 `SW1A 1AA`가 그렇다.
--
--   다섯 자리만 받으면 해외 장소의 우편번호를 담을 수 없다. 그러면
--   "밖에서 못 찾아와도 우리 기능이 멈추지 않는다"는 17-1.3절의 판단과
--   어긋난다. **우편번호 하나 때문에 그 장소를 못 담게 만들지 않는다.**
--
--   대신 길이를 짧게 잡고 빈 글자를 막는다. 우편번호로 셈을 하는 곳은 없다.
--   보여주고 찾는 값이다.
--
-- 빈 글자를 막는 규칙을 같은 모양으로 건다
--   `20260925235000`이 글 칸 여섯 개에 건 것과 같다. 카카오가 없는 값을
--   빈 글자로 준다는 것을 그때 알았고, 새 칸도 같은 자리에 있다.
--
-- 재실행 안전성
--   칸과 제약조건이 이미 있으면 건너뛴다.
-- =============================================================================

alter table public.place_profiles
  add column if not exists postal_code text;

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'place_profiles_postal_code_shape'
  ) then
    alter table public.place_profiles
      add constraint place_profiles_postal_code_shape check (
        postal_code is null
        or (
          pg_catalog.btrim(postal_code) <> ''
          and pg_catalog.char_length(postal_code) <= 20
        )
      );
  end if;
end
$$;

comment on column public.place_profiles.postal_code is
  '우편번호. 주소로 찾을 때만 온다. 해외는 글자가 섞이므로 다섯 자리로 못박지 않는다.';
