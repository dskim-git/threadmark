-- =============================================================================
-- 열쇠 칸에 기본값을 건다 (16-B, 3차례 뒤처리)
-- =============================================================================
-- **기본값은 타입을, 트리거는 실제 보장을 맡는다.**
--
-- 이 저장소가 이미 적어둔 규칙인데 한 칸에만 따랐다. 같은 파일 안에서
-- `owner_id`에는 기본값과 트리거를 둘 다 걸고 `token`에는 트리거만 걸었다.
-- 트리거가 채우니 됐다고 생각했고, 트리거는 실제로 채운다.
--
-- 빠진 것은 **타입 생성기에게 말해주는 쪽**이었다. 올린 뒤 `db:types`를
-- 돌려 보니 이렇게 나왔다.
--
--     Insert: {
--       owner_id?: string      // 선택 사항
--       token: string          // **필수**
--     }
--
-- 타입 생성기는 트리거를 모르고 **칸의 기본값만 본다.** 기본값이 없으니
-- `not null` 칸을 필수로 잡았다.
--
-- 그러면 공개를 켜는 코드가 **보내면 안 되는 값을 보내야 한다.** 우리가
-- 막으려던 것이 바로 그것이다. 열쇠를 클라이언트가 정하면 짧거나 뻔한
-- 열쇠를 넣을 수 있고, **주소를 맞혀서 열 수 있게 된다.** (16-B.5절)
--
-- 4-44절에서 `owner_id`가 똑같은 자리에 있었다. 그때 적어둔 것이 이것이다.
--
--   > 기본값을 빠뜨리면 타입 생성기가 트리거를 모르므로 owner_id를
--   > 필수로 보고, 코드가 보내면 안 되는 값을 보내야 한다.
--
-- 트리거는 그대로 둔다. **기본값이 보장이 아니다.** 기본값은 값을 보내지
-- 않았을 때만 쓰이고, 보냈으면 그 값이 들어간다. 보낸 값을 버리는 일은
-- 트리거만 할 수 있다. 두 겹이 하는 일이 다르다.
--
--   기본값  — 타입 생성기에게 "안 보내도 된다"고 말한다
--   트리거  — 보내도 **버린다**
--
-- 재실행 안전성
--   `alter column ... set default`는 여러 번 걸어도 같은 상태다.
-- =============================================================================

alter table public.project_public_links
  alter column token set default pg_catalog.replace(
    pg_catalog.gen_random_uuid()::text
      || pg_catalog.gen_random_uuid()::text,
    '-', ''
  );

comment on column public.project_public_links.token is
  '열쇠. 기본값은 타입을, 트리거는 실제 보장을 맡는다. 보낸 값은 트리거가 버린다. 주소를 맞혀서 열 수 없게 하는 유일한 장치다. (16-B.5절)';
