-- =============================================================================
-- 자료 상태에 '읽을 후보'를 더한다 (14-D-2b)
-- =============================================================================
-- 설계 문서 8.4절 마지막 줄.
-- "아직 등록하지 않은 논문은 reading_candidate로 저장한 뒤 정식 Source로
--  전환할 수 있게 한다."
--
-- 왜 새 표가 아니라 상태 하나인가
--   후보는 "아직 손에 없는 논문"이지 다른 종류의 것이 아니다. 별도 표에 담으면
--   제목·관계·서지 정보를 담는 길이 두 벌이 되고, 정식 자료로 바꿀 때 옮겨
--   담아야 한다. 옮기는 코드는 반드시 무언가를 빠뜨린다.
--
--   상태로 두면 전환이 곧 상태 바꾸기다. 옮길 것이 없고, 담아두는 순간부터
--   관계(8.4절)로 이을 수 있고, 서지 정보(8.1절)와 분석 서식(8.2절)도
--   그대로 쓴다. DOI만 적어두었다가 나중에 14-C의 가져오기로 채울 수 있다.
--
--   sources를 만들 때 이 열거형에 값을 하나만 두고 "실제로 필요해질 때
--   추가한다"고 적어두었다. (20260921090000) 그 자리다.
--
-- 이 파일은 값만 더한다
--   ALTER TYPE ... ADD VALUE로 더한 값은 **같은 트랜잭션에서 쓸 수 없다.**
--   Supabase CLI는 마이그레이션 파일마다 트랜잭션을 따로 잡으므로, 값을 쓰는
--   가드 트리거는 다음 파일(20260923211000)에 둔다. (AGENTS.md 6절)
--   13-C의 capture_verification_status가 같은 이유로 두 파일이었다.
-- =============================================================================

alter type public.source_status add value if not exists 'reading_candidate';
