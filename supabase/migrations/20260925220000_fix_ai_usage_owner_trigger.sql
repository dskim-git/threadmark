-- =============================================================================
-- AI 사용 장부의 소유자 트리거를 집안 방식으로 되돌린다 (16-A-1 고침)
-- =============================================================================
-- 무엇이 잘못됐나
--   `20260925210000_ai_usage_events.sql`의 트리거가 이렇게 되어 있었다.
--
--     new.owner_id := auth.uid();
--     if new.owner_id is null then raise exception ...
--
--   **로그인하지 않은 컨텍스트에서 넣는 길을 통째로 막았다.** 003 격리 검사가
--   검사용 줄을 미리 심을 때가 그 경우다. 검사가 이 오류로 멈췄다.
--
--     P0001: AI 사용 기록은 로그인한 사용자만 남길 수 있습니다.
--
-- 왜 눈치채지 못했나
--   **앱에서는 드러나지 않는다.** 앱은 언제나 로그인한 세션으로 넣으므로
--   `auth.uid()`가 늘 있다. `npm test`도 잡지 못한다. 그 검사들은 SQL을
--   실행하지 않고 글자만 읽는다.
--
--   드러난 자리가 003이었다. **실제로 돌려봐야만 나오는 고장이다.**
--   "검사가 다 통과해도 실제로 쓰면 문제가 나온다"가 이번에도 맞았다.
--
-- 무엇이 옳은 모양인가
--   이 저장소의 모든 소유자 트리거가 같은 모양이다.
--
--     if auth.uid() is not null then
--       new.owner_id := auth.uid();
--     end if;
--
--   `set_source_owner`, `set_media_watch_provider_owner`, 그 밖에 전부.
--   **있으면 덮어쓰고, 없으면 보낸 값을 그대로 둔다.**
--
--   보안은 그대로다. 지키려는 것은 "로그인한 사용자가 남의 이름으로 남기지
--   못한다"이고, 로그인한 세션에서는 `auth.uid()`가 늘 있어 반드시 덮어쓴다.
--   (003의 검사 118이 그것을 재는 자리다)
--
--   `auth.uid()`가 없는 컨텍스트는 `postgres`와 `service_role`뿐이다. 그쪽은
--   이미 무엇이든 할 수 있으므로 여기서 막는 것에 뜻이 없었다. **막을 수
--   없는 것을 막으려다 막지 말아야 할 것을 막았다.**
--
--   owner_id가 비는 경우는 열의 `not null`이 잡는다. 트리거가 따로 외칠
--   이유가 없다.
--
-- 왜 앞의 파일을 고치지 않고 새로 만드는가
--   앞의 것은 이미 원격에 올라갔다. 올라간 마이그레이션을 고치면 로컬과
--   원격의 기록이 어긋나고, 그 어긋남은 다음 사람이 알 길이 없다.
-- =============================================================================

create or replace function public.set_ai_usage_event_owner()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  -- 로그인한 세션이면 보낸 값을 무시하고 덮어쓴다. 남의 한도를 대신 쓰지 못한다.
  if auth.uid() is not null then
    new.owner_id := auth.uid();
  end if;

  -- 시각은 언제나 서버가 정한다. 보낸 값을 믿으면 지난달로 적어 한도를 비켜 간다.
  new.created_at := pg_catalog.now();

  return new;
end;
$$;

