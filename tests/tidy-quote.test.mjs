/**
 * 집은 문장을 얼마나 다듬었는지 재는 셈. (2026-10-04, 사용자 요청)
 *
 * 다듬는 길을 열면서 **그 길이 고쳐 쓰는 길이 되지 않게** 재는 자리다.
 *
 * 이 셈이 느슨하면 아무 말도 하지 않고, 빡빡하면 띄어쓰기 하나 고칠 때마다
 * 경고가 뜬다. **둘 다 경고를 무시하게 만든다.**
 *
 * 실행: npm test
 */

import assert from "node:assert/strict";
import test from "node:test";

import {
  heavilyChanged,
  quoteToSave,
} from "../src/lib/captures/tidy-quote.ts";

// -----------------------------------------------------------------------------
// 다듬은 것으로 보는 것
// -----------------------------------------------------------------------------

test("띄어쓰기를 고친 것은 다듬은 것이다", () => {
  /*
    사용자가 말한 경우다. PDF의 글자는 보이지 않는 조각 수백 개라
    줄이 바뀌는 자리에서 띄어쓰기가 끼어든다.
  */
  assert.equal(
    heavilyChanged("그것은 우 리 의식이", "그것은 우리 의식이"),
    false,
  );
});

test("빠진 마침표를 더한 것은 다듬은 것이다", () => {
  // 드래그가 끝의 문장부호까지 못 집는 일이 잦다.
  assert.equal(
    heavilyChanged("움직여나가기 때문이오", "움직여나가기 때문이오."),
    false,
  );
});

test("따옴표 짝을 맞춘 것도 다듬은 것이다", () => {
  // PDF는 여는 따옴표와 닫는 따옴표를 따로 담는다. 한쪽만 들어오는 일이 있다.
  assert.equal(heavilyChanged("그는 “말했다", "그는 “말했다”"), false);
});

test("줄바꿈이 사라진 것도 다듬은 것이다", () => {
  assert.equal(heavilyChanged("앞줄\n뒷줄", "앞줄 뒷줄"), false);
});

test("아무것도 안 고쳤으면 당연히 다듬은 것이다", () => {
  assert.equal(heavilyChanged("같은 문장", "같은 문장"), false);
});

// -----------------------------------------------------------------------------
// 고쳐 쓴 것으로 보는 것
// -----------------------------------------------------------------------------

test("낱말을 바꾸면 알린다", () => {
  assert.equal(heavilyChanged("구별을 지으려 하는", "구분을 지으려 하는"), true);
});

test("길이가 같아도 뜻이 뒤집히면 알린다", () => {
  /*
    **길이만 재는 길이 틀리는 자리다.** `있소`와 `없소`는 길이가 같고,
    뜻이 뒤집히는데 아무 말도 하지 않는다.
  */
  assert.equal(heavilyChanged("경향이 있소", "경향이 없소"), true);
});

test("말을 덧붙이면 알린다", () => {
  assert.equal(
    heavilyChanged("사람들은 구별을 지으려 한다", "사람들은 늘 구별을 지으려 한다"),
    true,
  );
});

test("문장을 지우면 알린다", () => {
  assert.equal(heavilyChanged("앞 문장. 뒤 문장.", "앞 문장."), true);
});

// -----------------------------------------------------------------------------
// 담길 글 고르기
// -----------------------------------------------------------------------------

test("다듬지 않았으면 집은 그대로 담는다", () => {
  assert.equal(quoteToSave("집은 문장", null), "집은 문장");
});

test("다 지웠으면 집은 그대로 담는다", () => {
  /*
    **원문 없는 인용은 인용이 아니다.** (설계 문서 2.4절) 데이터베이스의
    제약조건도 막는다. 여기서 먼저 걸러 저장이 실패하는 대신 집은 것이
    담기게 한다.
  */
  assert.equal(quoteToSave("집은 문장", ""), "집은 문장");
  assert.equal(quoteToSave("집은 문장", "   "), "집은 문장");
});

test("다듬었으면 다듬은 것을 담는다", () => {
  assert.equal(quoteToSave("우 리 의식", "우리 의식."), "우리 의식.");
});

test("앞뒤 공백은 떼고 담는다", () => {
  assert.equal(quoteToSave("집은 문장", "  다듬은 문장  "), "다듬은 문장");
});
