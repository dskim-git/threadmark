// 파일 이름
// -----------------------------------------------------------------------------

test("파일 이름에 날짜가 들어간다", () => {
  /*
    두 번 내려받으면 `(1)`이 붙어 어느 것이 최신인지 알 수 없게 된다.
    날짜가 있으면 파일 이름만 보고 안다.
  */
  const name = exportFileName("captures", "csv");

  assert.match(name, /^threadmark-captures-\d{4}-\d{2}-\d{2}\.csv$/u);
});

test("파일 이름에 영문과 숫자만 쓴다", () => {
  // 운영체제마다 한글 파일 이름을 다루는 방식이 다르다.
  assert.match(exportFileName("all", "json"), /^[A-Za-z0-9.-]+$/u);
});
