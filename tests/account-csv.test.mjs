/**
 * 표 파일(CSV) 만들기의 단위 검사. (18단계, 내려받기)
 *
 * **이 잘못은 눈에 띄지 않는다.** 파일은 멀쩡히 만들어지고 열면 표처럼
 * 보인다. 수백 줄 중 쉼표가 든 몇 줄만 칸이 밀려 있고, 그 줄에서는
 * 메모가 엉뚱한 칸에 들어가 있다.
 *
 * 우리가 담는 글에는 쉼표도 따옴표도 줄바꿈도 있다. **인용한 문장이 특히
 * 그렇다.** 그러니 이 규칙이 맞는지는 눌러보는 것으로 알 수 없다.
 *
 * 실행: npm test
 */

import assert from "node:assert/strict";
import test from "node:test";

import {
  CSV_BOM,
  csvCell,
  exportFileName,
  toCsv,
} from "../src/lib/account/csv.ts";

// -----------------------------------------------------------------------------
// 한 칸
// -----------------------------------------------------------------------------

test("보통 글은 그대로 둔다", () => {
  assert.equal(csvCell("서론"), "서론");
  assert.equal(csvCell(42), "42");
});

test("쉼표가 들어 있으면 감싼다", () => {
  // 감싸지 않으면 한 칸이 두 칸이 된다.
  assert.equal(csvCell("김대수, 이서연"), '"김대수, 이서연"');
});

test("따옴표는 두 번 적고 감싼다", () => {
  /*
    `그는 "아니오"라고 했다` → `"그는 ""아니오""라고 했다"`
    한 번만 적으면 그 자리에서 칸이 끝난 것으로 읽힌다.
  */
  assert.equal(csvCell('그는 "아니오"라고 했다'), '"그는 ""아니오""라고 했다"');
});

test("줄바꿈이 들어 있으면 감싼다", () => {
  // 인용한 문장에 줄바꿈이 흔하다. 감싸지 않으면 한 줄이 두 줄이 된다.
  assert.equal(csvCell("첫 줄\n둘째 줄"), '"첫 줄\n둘째 줄"');
  assert.equal(csvCell("첫 줄\r\n둘째 줄"), '"첫 줄\r\n둘째 줄"');
});

test("빈 값은 빈 칸이다", () => {
  /*
    **`null`이라는 글자를 적지 않는다.** 표를 열어본 사람이 그것을 자기가
    적은 값으로 읽게 된다.
  */
  assert.equal(csvCell(null), "");
  assert.equal(csvCell(undefined), "");
  assert.equal(csvCell(""), "");
});

test("목록은 세미콜론으로 잇는다", () => {
  /*
    쉼표로 이으면 칸을 나누는 글자와 같아진다. 감싸더라도 표를 여는 사람이
    한 칸인지 여러 칸인지 헷갈린다. 태그와 저자 이름이 이 길로 온다.
  */
  assert.equal(csvCell(["수학", "평가"]), "수학; 평가");
  assert.equal(csvCell([]), "");
});

test("목록 안의 빈 값도 무너지지 않는다", () => {
  assert.equal(csvCell(["수학", null, "평가"]), "수학; ; 평가");
});

test("목록 안에 쉼표가 있으면 전체를 감싼다", () => {
  assert.equal(csvCell(["김, 이", "박"]), '"김, 이; 박"');
});

// -----------------------------------------------------------------------------
// 한 덩어리
// -----------------------------------------------------------------------------

test("머리줄과 값줄을 만든다", () => {
  const csv = toCsv(["제목", "유형"], [["서론", "논문"]]);

  assert.equal(csv, `${CSV_BOM}제목,유형\r\n서론,논문\r\n`);
});

test("엑셀이 한글을 알아보게 하는 표시를 맨 앞에 붙인다", () => {
  /*
    **없으면 엑셀이 한글을 깨뜨린다.** `기록`이 `湲곕줉`처럼 나온다.
    내려받아 여는 사람의 대부분이 엑셀을 쓴다.
  */
  assert.ok(toCsv(["a"], []).startsWith(CSV_BOM));
});

test("줄 끝이 CRLF다", () => {
  // RFC 4180이 그렇게 정했고 윈도우 엑셀이 그것을 기대한다.
  const csv = toCsv(["a", "b"], [["1", "2"], ["3", "4"]]);

  assert.equal(csv.slice(CSV_BOM.length), "a,b\r\n1,2\r\n3,4\r\n");
});

test("값이 없어도 머리줄은 남는다", () => {
  /*
    담아둔 것이 없는 사람이 내려받으면 빈 파일이 온다. 머리줄까지 없으면
    **파일이 고장 난 것처럼 보인다.** 칸 이름만 있는 표는 "아직 없다"로
    읽힌다.
  */
  assert.equal(toCsv(["제목"], []), `${CSV_BOM}제목\r\n`);
});

test("칸이 밀리지 않는다", () => {
  /*
    이 검사가 이 파일의 핵심이다. 쉼표·따옴표·줄바꿈이 한꺼번에 든 줄을
    만들고, 되읽었을 때 칸 수가 그대로인지 본다.
  */
  const nasty = '인용: "첫째, 둘째"\n그리고 셋째';
  const csv = toCsv(["제목", "내용", "태그"], [["논문", nasty, ["수학", "평가"]]]);

  // 감싼 칸 밖의 쉼표만 칸을 나눈다. 값줄에서 밖에 있는 쉼표는 둘이다.
  const body = csv.slice(CSV_BOM.length).split("\r\n")[1] ?? "";
  let inQuotes = false;
  let separators = 0;

  for (const char of body) {
    if (char === '"') {
      inQuotes = !inQuotes;
    } else if (char === "," && !inQuotes) {
      separators += 1;
    }
  }

  assert.equal(separators, 2, "칸이 밀렸다");
});

